def _bnida(m):
    """받침 ㅂ + "니다." → 받침 ㄴ + "다." (드립니다 → 드린다)"""
    ch = m.group(1)
    code = ord(ch) - 0xAC00
    if 0 <= code < 11172 and code % 28 == 17:      # 종성이 ㅂ일 때만
        return chr(0xAC00 + code - 17 + 4) + "다."  # ㅂ(17) → ㄴ(4)
    return m.group(0)


def _iraye(m):
    """"~입니다." → 받침 없으면 "라예.", 있으면 "이라예."

    2026-11-15 추가. 그 전까지 "입니다." 를 통째로 "이라예." 로 바꿔서
    받침 없는 명사 뒤에 "변수이라예 / 호재이라예" 처럼 '이'가 덧붙었다.
    경남말은 "변수라예 / 호재라예" 라고 한다.
    """
    ch = m.group(1)
    code = ord(ch) - 0xAC00
    if 0 <= code < 11172 and code % 28 == 0:       # 종성이 없으면
        return ch + "라예."
    return ch + "이라예."


