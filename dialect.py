def _bnida(m):
    """받침 ㅂ + "니다." → 받침 ㄴ + "다." (드립니다 → 드린다)"""
    ch = m.group(1)
    code = ord(ch) - 0xAC00
    if 0 <= code < 11172 and code % 28 == 17:      # 종성이 ㅂ일 때만
        return chr(0xAC00 + code - 17 + 4) + "다."  # ㅂ(17) → ㄴ(4)
    return m.group(0)


